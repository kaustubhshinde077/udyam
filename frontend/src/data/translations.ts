const rawTranslations: Record<string, TranslationDictionary> = {
  en,
  hi,
  mr,
  English: en,
  Hindi: hi,
  Marathi: mr,
};

// Proxied translations so no key ever returns undefined
function createSafeDict(dict: TranslationDictionary, fallbackDict: TranslationDictionary): TranslationDictionary {
  return new Proxy(dict, {
    get(target, prop: string) {
      if (prop in target && target[prop] !== undefined && target[prop] !== '') {
        return target[prop];
      }
      if (prop in fallbackDict && fallbackDict[prop] !== undefined) {
        return fallbackDict[prop];
      }
      return prop;
    },
  });
}

const safeEn = createSafeDict(en, en);
const safeHi = createSafeDict(hi, en);
const safeMr = createSafeDict(mr, en);

export const UI_TRANSLATIONS: Record<string, TranslationDictionary> = new Proxy(rawTranslations, {
  get(target, prop: string) {
    if (prop === 'hi' || prop === 'Hindi') return safeHi;
    if (prop === 'mr' || prop === 'Marathi') return safeMr;
    return safeEn;
  },
});
